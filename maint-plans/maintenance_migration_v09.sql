    TemplateCode, TierCode, ExpectedYears, IsActive
) VALUES (
    source.TemplateCode, source.TierCode, source.ExpectedYears, source.IsActive
);
GO

MERGE dbo.MaintenanceLifecycleStages AS target
USING (VALUES
    (N'Early Life', 0.4, 10, 1),
    (N'Mid Life', 0.7, 20, 1),
    (N'Mature', 0.9, 30, 1),
    (N'Replacement Planning', 999, 40, 1)
) AS source (StageLabel, MaxAgeRatio, SortOrder, IsActive)
