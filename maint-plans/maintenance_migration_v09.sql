/*
   Protocol assignment: which template applies to a given appliance.

   This is the SQL form of WILSON_PROTOCOL.resolveCheckpointSet() in
   plan-config.js. Resolution walks assignments in Precedence order and takes
   the first active match:

       Precedence 10  APPLIANCE_TYPE      matched on MaintenanceAssets.AssetTypeCode
       Precedence 20  CUSTOMER_CATEGORY   matched on MaintenanceAssets.CustomerCategoryCode

   MaintenanceAssets.CheckpointSetCode remains as the value captured at
   enrollment, but it is a snapshot, NOT the resolution input -- exactly as in
   the JS resolver. Assets created before v0.9.1 hold four known-wrong values
   (Ventilation as generic, Microwave as cooking, Washer and Dryer as laundry);
   resolving through these assignments corrects them with no data migration.
   IMUC group membership still wins over both scopes and is applied in code.
*/
