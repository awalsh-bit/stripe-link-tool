- Retiring the office-built report tables (MaintenanceHealthReport* still carry
  the pre-v0.7 model). They are left intact because live prototype data may
  reference them; plan their retirement with the API contract rewrite.
- Photo binary storage. Only the storage key is modelled -- see MERGE_GUIDE
  section 20.
- HVAC field protocols. No HVAC field workflow exists yet (context section 34
  item 3), so no HVAC protocol templates are seeded.

Security
