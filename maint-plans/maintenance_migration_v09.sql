are enforced with CHECK constraints, so a UI phrase can never be persisted as
state.

Applying this script
--------------------
Run sql/maintenance_schema.sql first. This script is strictly additive and
idempotent: every object is guarded, every column addition is guarded by
COL_LENGTH, and every seed is a MERGE. Re-running it is safe and is the
intended way to pick up protocol changes.

It deliberately does NOT redefine any existing object. sql/maintenance_schema.sql
ends with three CREATE OR ALTER VIEW statements; if this migration altered one of
them, a later re-run of the base script would silently revert it. New behaviour
is therefore delivered as new views instead.

Not covered here
