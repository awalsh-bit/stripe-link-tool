/*
   Payment readiness. MERGE_GUIDE 7.2: an AR household is payment-ready even
   with no Stripe payment method, so readiness must never be inferred from a
   missing card.
*/
CREATE OR ALTER VIEW dbo.vw_MaintenanceHouseholdPaymentReadiness
AS
SELECT
    h.HouseholdId,
    h.HouseholdReference,
    h.DisplayName AS HouseholdName,
    h.BillingMethodCode,
    h.AccountTerms,
    h.ARStatus,
    h.ExternalARCustomerId,
    pp.PaymentProfileId,
    pp.PaymentProfileStatus,
    pp.CardBrand,
    pp.CardLast4,
    CAST(
        CASE
            WHEN h.BillingMethodCode = 'AR_ACCOUNT'
                 AND ISNULL(h.ARStatus, 'Review') = 'Active' THEN 1
            WHEN h.BillingMethodCode = 'CARD_ON_FILE'
                 AND pp.PaymentProfileId IS NOT NULL
                 AND pp.PaymentProfileStatus = 'Active' THEN 1
            ELSE 0
        END AS BIT
    ) AS PaymentReady,
    CASE
        WHEN h.BillingMethodCode = 'AR_ACCOUNT'
             AND ISNULL(h.ARStatus, 'Review') = 'Active' THEN 'AR_APPROVED'
        WHEN h.BillingMethodCode = 'AR_ACCOUNT' THEN 'ACTION_REQUIRED'
        WHEN pp.PaymentProfileId IS NULL THEN 'ACTION_REQUIRED'
        WHEN pp.PaymentProfileStatus <> 'Active' THEN 'ACTION_REQUIRED'
        ELSE 'READY_TO_CHARGE'
    END AS PaymentReadinessCode
FROM dbo.MaintenanceHouseholds h
OUTER APPLY (
    SELECT TOP (1)
        p.PaymentProfileId, p.PaymentProfileStatus, p.CardBrand, p.CardLast4
    FROM dbo.MaintenancePaymentProfiles p
    WHERE p.HouseholdId = h.HouseholdId
    ORDER BY
        CASE WHEN p.PaymentProfileStatus = 'Active' THEN 0 ELSE 1 END,
        p.PaymentProfileId DESC
) pp;
GO

/*
   Field progress per visit. Drives the Command Center's view of what the
   technician has finished and whether the report package is ready
   (MERGE_GUIDE 23).
*/
CREATE OR ALTER VIEW dbo.vw_MaintenanceFieldProgress
AS
SELECT
    v.VisitId,
    v.HouseholdId,
    h.DisplayName AS HouseholdName,
    v.DueDate,
    v.VisitStatus,
    v.AssignedTechnicianUserId,
    v.AssignedTechnicianNameSnapshot,
    v.FieldStartedAt,
    v.CompletedAt,
    COUNT(va.VisitAssetId) AS ScopedAssetCount,
    SUM(CASE WHEN fi.InspectionStatus IN ('FIELD_COMPLETE', 'REPORT_GENERATED')
             THEN 1 ELSE 0 END) AS CompletedAssetCount,
    SUM(CASE WHEN fi.InspectionStatus = 'IN_PROGRESS' THEN 1 ELSE 0 END)
        AS InProgressAssetCount,
    SUM(CASE WHEN fi.FieldInspectionId IS NULL
                   OR fi.InspectionStatus = 'NOT_STARTED'
             THEN 1 ELSE 0 END) AS NotStartedAssetCount,
    SUM(CASE WHEN fi.FollowUpRequired = 1 THEN 1 ELSE 0 END) AS FollowUpCount,
    CAST(
        CASE WHEN COUNT(va.VisitAssetId) > 0
              AND COUNT(va.VisitAssetId) = SUM(
                    CASE WHEN fi.InspectionStatus IN ('FIELD_COMPLETE', 'REPORT_GENERATED')
                         THEN 1 ELSE 0 END)
             THEN 1 ELSE 0 END AS BIT
    ) AS AllAssetsFieldComplete,
    AVG(CAST(fi.FinalHealthScore AS DECIMAL(6,2))) AS AverageHealthScore
FROM dbo.MaintenanceVisits v
INNER JOIN dbo.MaintenanceHouseholds h
    ON h.HouseholdId = v.HouseholdId
LEFT JOIN dbo.MaintenanceVisitAssets va
    ON va.VisitId = v.VisitId
LEFT JOIN dbo.MaintenanceFieldInspections fi
    ON fi.VisitId = va.VisitId
   AND fi.AssetId = va.AssetId
GROUP BY
    v.VisitId, v.HouseholdId, h.DisplayName, v.DueDate, v.VisitStatus,
    v.AssignedTechnicianUserId, v.AssignedTechnicianNameSnapshot,
    v.FieldStartedAt, v.CompletedAt;
GO

/*
   Resolved protocol per asset. The SQL counterpart of
   WILSON_PROTOCOL.resolveCheckpointSet(), including the IMUC override.
   Compare against MaintenanceAssets.CheckpointSetCode to find assets still
   carrying a stale snapshot.
*/
CREATE OR ALTER VIEW dbo.vw_MaintenanceAssetProtocol
AS
SELECT
    resolution.AssetId,
    resolution.HouseholdId,
    resolution.AssetCategory,
    resolution.AssetTypeCode,
    resolution.AssetTypeName,
    resolution.CustomerCategoryCode,
    resolution.StoredCheckpointSetCode,
    resolution.ResolvedTemplateCode,
    CAST(CASE WHEN resolution.StoredCheckpointSetCode IS NOT NULL
                   AND resolution.StoredCheckpointSetCode <> resolution.ResolvedTemplateCode
              THEN 1 ELSE 0 END AS BIT) AS StoredValueIsStale
FROM (
    /* Non-IMUC: assignment by precedence, then the stored snapshot only if it
       names a real template, then generic. The snapshot ranks BELOW config and
       above generic -- identical to step 4 of resolveCheckpointSet(). */
    SELECT
        a.AssetId,
        a.HouseholdId,
        a.AssetCategory,
        a.AssetTypeCode,
        a.AssetTypeName,
        a.CustomerCategoryCode,
        a.CheckpointSetCode AS StoredCheckpointSetCode,
        COALESCE(resolved.TemplateCode, snapshot.TemplateCode, 'generic')
            AS ResolvedTemplateCode
    FROM dbo.MaintenanceAssets a
    OUTER APPLY (
        SELECT TOP (1) pa.TemplateCode
        FROM dbo.MaintenanceProtocolAssignments pa
        WHERE pa.IsActive = 1
          AND (
                (pa.AssignmentScope = 'APPLIANCE_TYPE' AND pa.ScopeCode = a.AssetTypeCode)
             OR (pa.AssignmentScope = 'CUSTOMER_CATEGORY' AND pa.ScopeCode = a.CustomerCategoryCode)
          )
        ORDER BY pa.Precedence, pa.ProtocolAssignmentId
    ) resolved
    OUTER APPLY (
        SELECT TOP (1) t.TemplateCode
        FROM dbo.MaintenanceProtocolTemplates t
        WHERE t.TemplateCode = a.CheckpointSetCode
          AND t.IsActive = 1
        ORDER BY t.TemplateVersion DESC
    ) snapshot
    WHERE a.AssetCategory <> 'imuc'

    UNION ALL

    /* IMUC group membership always wins, before any assignment lookup. */
    SELECT
        a.AssetId,
        a.HouseholdId,
        a.AssetCategory,
        a.AssetTypeCode,
        a.AssetTypeName,
        a.CustomerCategoryCode,
        a.CheckpointSetCode AS StoredCheckpointSetCode,
        'icemaker' AS ResolvedTemplateCode
    FROM dbo.MaintenanceAssets a
    WHERE a.AssetCategory = 'imuc'
) resolution;
GO

