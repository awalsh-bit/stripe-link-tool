/* -------------------------------------------------------------------------
   7.8  Filter service pricing  (beyond MERGE_GUIDE section 7)

   Filter service is now a PRICED selection rather than a flag: choosing it on
   an individual refrigeration or icemaker asset raises the annual plan price by
   Wilson's sales price for that asset's filters. Estate Concierge includes
   filters outright, so the same selection costs nothing there.

   Water and air / food-preservation filters are separate customer choices --
   air is common on Sub-Zero and similar premium refrigeration and is never
   selected by default.

   PLACEHOLDER PRICING. The seeded unit prices mirror the $70 placeholder in
   assets/plan-config.js and are NOT approved numbers. When Wilson's filter
   sales-price list is loaded, add rows keyed by PartNumber (leaving the
   kind-level rows as the fallback) and set PriceIsPlaceholder = 0. Pricing
   should be resolved server-side from this table rather than from browser JS
   (context section 34 item 11).
   ------------------------------------------------------------------------- */
IF OBJECT_ID('dbo.MaintenanceFilterPrices', 'U') IS NULL
BEGIN
    CREATE TABLE dbo.MaintenanceFilterPrices (
        FilterPriceId INT IDENTITY(1,1) NOT NULL
            CONSTRAINT PK_MaintenanceFilterPrices PRIMARY KEY,
        FilterKindCode NVARCHAR(20) NOT NULL,
        /* NULL PartNumber = the kind-level fallback price. */
        PartNumber NVARCHAR(100) NULL,
        FilterDescription NVARCHAR(300) NULL,
        UnitSalesPrice DECIMAL(12,2) NOT NULL,
        DefaultQuantity INT NOT NULL
            CONSTRAINT DF_MaintenanceFilterPrices_Quantity DEFAULT (1),
        PriceIsPlaceholder BIT NOT NULL
            CONSTRAINT DF_MaintenanceFilterPrices_Placeholder DEFAULT (1),
        EffectiveFrom DATE NULL,
        EffectiveTo DATE NULL,
        IsActive BIT NOT NULL
            CONSTRAINT DF_MaintenanceFilterPrices_Active DEFAULT (1),
        CreatedAt DATETIME2 NOT NULL
            CONSTRAINT DF_MaintenanceFilterPrices_CreatedAt DEFAULT SYSUTCDATETIME(),
        UpdatedAt DATETIME2 NOT NULL
            CONSTRAINT DF_MaintenanceFilterPrices_UpdatedAt DEFAULT SYSUTCDATETIME(),
        CONSTRAINT CK_MaintenanceFilterPrices_Kind
            CHECK (FilterKindCode IN ('water', 'air')),
        CONSTRAINT CK_MaintenanceFilterPrices_Price
            CHECK (UnitSalesPrice >= 0)
    );

    /* One fallback row per kind; part-number rows are added alongside. */
    CREATE UNIQUE INDEX UX_MaintenanceFilterPrices_KindFallback
        ON dbo.MaintenanceFilterPrices(FilterKindCode)
        WHERE PartNumber IS NULL;

    CREATE UNIQUE INDEX UX_MaintenanceFilterPrices_Part
        ON dbo.MaintenanceFilterPrices(FilterKindCode, PartNumber)
        WHERE PartNumber IS NOT NULL;
END;
GO

