/*
   Resolved protocol per asset. The SQL counterpart of
   WILSON_PROTOCOL.resolveCheckpointSet(), including the IMUC override.
   Compare against MaintenanceAssets.CheckpointSetCode to find assets still
   carrying a stale snapshot.
*/
CREATE OR ALTER VIEW dbo.vw_MaintenanceAssetProtocol
AS
SELECT
    resolution.AssetId,
    resolution.HouseholdId,
    resolution.AssetCategory,
    resolution.AssetTypeCode,
    resolution.AssetTypeName,
    resolution.CustomerCategoryCode,
    resolution.StoredCheckpointSetCode,
    resolution.ResolvedTemplateCode,
    CAST(CASE WHEN resolution.StoredCheckpointSetCode IS NOT NULL
                   AND resolution.StoredCheckpointSetCode <> resolution.ResolvedTemplateCode
              THEN 1 ELSE 0 END AS BIT) AS StoredValueIsStale
FROM (
    /* Non-IMUC: assignment by precedence, then the stored snapshot only if it
       names a real template, then generic. The snapshot ranks BELOW config and
       above generic -- identical to step 4 of resolveCheckpointSet(). */
    SELECT
        a.AssetId,
        a.HouseholdId,
        a.AssetCategory,
        a.AssetTypeCode,
        a.AssetTypeName,
        a.CustomerCategoryCode,
        a.CheckpointSetCode AS StoredCheckpointSetCode,
        COALESCE(resolved.TemplateCode, snapshot.TemplateCode, 'generic')
            AS ResolvedTemplateCode
    FROM dbo.MaintenanceAssets a
    OUTER APPLY (
        SELECT TOP (1) pa.TemplateCode
        FROM dbo.MaintenanceProtocolAssignments pa
        WHERE pa.IsActive = 1
          AND (
                (pa.AssignmentScope = 'APPLIANCE_TYPE' AND pa.ScopeCode = a.AssetTypeCode)
             OR (pa.AssignmentScope = 'CUSTOMER_CATEGORY' AND pa.ScopeCode = a.CustomerCategoryCode)
          )
        ORDER BY pa.Precedence, pa.ProtocolAssignmentId
    ) resolved
    OUTER APPLY (
        SELECT TOP (1) t.TemplateCode
        FROM dbo.MaintenanceProtocolTemplates t
        WHERE t.TemplateCode = a.CheckpointSetCode
          AND t.IsActive = 1
        ORDER BY t.TemplateVersion DESC
    ) snapshot
    WHERE a.AssetCategory NOT IN ('imuc', 'hvac')

    UNION ALL

    /* HVAC resolves by SYSTEM TYPE, never by an appliance-type assignment.
       This arm was missing, and its absence was invisible: with no HVAC assets
       in the demo data and no HVAC case in the parity test, the view happily
       resolved an HVAC asset to whatever appliance template its type code
       happened to match. The JS resolver (WILSON_PROTOCOL.resolveCheckpointSet)
       branches on group === 'hvac' first, in this order, and falls through to
       'generic' on purpose: an unrecognised system should be visible as a gap
       rather than quietly get three subjective ratings. */
    SELECT
        a.AssetId,
        a.HouseholdId,
        a.AssetCategory,
        a.AssetTypeCode,
        a.AssetTypeName,
        a.CustomerCategoryCode,
        a.CheckpointSetCode AS StoredCheckpointSetCode,
        CASE
            WHEN systype.SystemType LIKE '%heat pump%'
              OR systype.SystemType LIKE '%heatpump%'      THEN 'hvac_heatpump'
            WHEN systype.SystemType LIKE '%mini split%'
              OR systype.SystemType LIKE '%mini-split%'
              OR systype.SystemType LIKE '%minisplit%'
              OR systype.SystemType LIKE '%ductless%'      THEN 'hvac_minisplit'
            WHEN systype.SystemType LIKE '%furnace%'
              OR systype.SystemType LIKE '%gas heat%'      THEN 'hvac_furnace'
            WHEN systype.SystemType LIKE '%split%'
              OR systype.SystemType LIKE '%package%'
              OR systype.SystemType LIKE '%air handler%'
              OR systype.SystemType LIKE '%condenser%'     THEN 'hvac_cooling'
            ELSE 'generic'
        END AS ResolvedTemplateCode
    FROM dbo.MaintenanceAssets a
    CROSS APPLY (
        SELECT LOWER(COALESCE(NULLIF(a.AssetTypeCode, N''),
                              NULLIF(a.AssetTypeName, N''),
                              a.CustomerCategoryCode, N'')) AS SystemType
    ) systype
    WHERE a.AssetCategory = 'hvac'

    UNION ALL

    /* IMUC group membership always wins, before any assignment lookup. */
    SELECT
        a.AssetId,
        a.HouseholdId,
        a.AssetCategory,
        a.AssetTypeCode,
        a.AssetTypeName,
        a.CustomerCategoryCode,
        a.CheckpointSetCode AS StoredCheckpointSetCode,
        'icemaker' AS ResolvedTemplateCode
    FROM dbo.MaintenanceAssets a
    WHERE a.AssetCategory = 'imuc'
) resolution;
GO

