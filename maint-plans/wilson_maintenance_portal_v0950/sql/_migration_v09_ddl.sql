/* -------------------------------------------------------------------------
   The current water for each household, resolved.

   THE FACTOR IS COMPUTED HERE, FROM THE READING. This view carries the same
   algorithm as WILSON_WATER.lifeFactorForGpg() in plan-config.js and the two
   must not drift:

     - at or below the first anchor  -> 1.000
     - at or above the last anchor   -> that anchor's factor, FLAT
     - between two anchors           -> linear, rounded to 3 decimals

   The rounding is part of the contract, not an implementation detail. Without
   it the two sides agree to fourteen decimal places and disagree in the
   fifteenth, which is enough to print a different number of years.

   A household with no test does not appear here. Absence means untested, which
   means no adjustment -- callers must LEFT JOIN and treat a miss as a factor of
   1.00 rather than filtering the household out of a report.
   ------------------------------------------------------------------------- */
IF OBJECT_ID('dbo.vw_MaintenanceHouseholdWaterLatest', 'V') IS NOT NULL
    DROP VIEW dbo.vw_MaintenanceHouseholdWaterLatest;
GO

CREATE VIEW dbo.vw_MaintenanceHouseholdWaterLatest
AS
WITH latest AS (
    SELECT t.*,
           ROW_NUMBER() OVER (PARTITION BY t.HouseholdId
                              ORDER BY t.TestedOn DESC, t.WaterTestId DESC) AS rn
    FROM dbo.MaintenanceHouseholdWaterTests t
),
bounds AS (
    SELECT MIN(GrainsPerGallon) AS FirstGpg, MAX(GrainsPerGallon) AS LastGpg
    FROM dbo.MaintenanceWaterLifeFactorAnchors WHERE IsActive = 1
),
interpolated AS (
    SELECT
        l.HouseholdId, l.WaterTestId, l.VisitId, l.GrainsPerGallon,
        l.TestedOn, l.TestedByName,
        CAST(CASE
            /* Flat below the first anchor and above the last. */
            WHEN l.GrainsPerGallon <= bd.FirstGpg THEN
                (SELECT LifeFactor FROM dbo.MaintenanceWaterLifeFactorAnchors
                 WHERE GrainsPerGallon = bd.FirstGpg)
            WHEN l.GrainsPerGallon >= bd.LastGpg THEN
                (SELECT LifeFactor FROM dbo.MaintenanceWaterLifeFactorAnchors
                 WHERE GrainsPerGallon = bd.LastGpg)
            /* Linear between the two anchors that bracket the reading. */
            ELSE ROUND(
                lo.LifeFactor
                + ((l.GrainsPerGallon - lo.GrainsPerGallon)
                   / NULLIF(hi.GrainsPerGallon - lo.GrainsPerGallon, 0))
                  * (hi.LifeFactor - lo.LifeFactor), 3)
        END AS DECIMAL(4,3)) AS LifeFactor
    FROM latest l
    CROSS JOIN bounds bd
    /* `an`, not `a`: throughout this migration `a.` is MaintenanceAssets, and
       reusing it here for the anchor table read as an asset column to anything
       scanning the file -- including this package's own schema checker, which
       is what caught it. */
    OUTER APPLY (
        SELECT TOP (1) an.GrainsPerGallon, an.LifeFactor
        FROM dbo.MaintenanceWaterLifeFactorAnchors an
        WHERE an.IsActive = 1 AND an.GrainsPerGallon <= l.GrainsPerGallon
        ORDER BY an.GrainsPerGallon DESC
    ) lo
    OUTER APPLY (
        SELECT TOP (1) an.GrainsPerGallon, an.LifeFactor
        FROM dbo.MaintenanceWaterLifeFactorAnchors an
        WHERE an.IsActive = 1 AND an.GrainsPerGallon > l.GrainsPerGallon
        ORDER BY an.GrainsPerGallon ASC
    ) hi
    WHERE l.rn = 1
)
SELECT
    i.HouseholdId,
    i.WaterTestId,
    i.VisitId,
    i.GrainsPerGallon,
    i.TestedOn,
    i.TestedByName,
    /* The band names the reading for the customer. It carries no arithmetic --
       the factor above came from the number, not from this. */
    b.BandCode,
    b.DisplayName AS BandName,
    b.PlainLanguage,
    /* The flag the customer's report shows. */
    CASE WHEN b.SortOrder >= fb.SortOrder THEN CAST(1 AS BIT) ELSE CAST(0 AS BIT) END
        AS IsFlaggedToCustomer,
    i.LifeFactor,
    cfg.Basis,
    cfg.IsSourced
FROM interpolated i
CROSS JOIN dbo.MaintenanceWaterHardnessSettings cfg
INNER JOIN dbo.MaintenanceWaterHardnessBands fb
    ON fb.BandCode = cfg.CustomerFlagBandCode
OUTER APPLY (
    SELECT TOP (1) bb.BandCode, bb.DisplayName, bb.PlainLanguage, bb.SortOrder
    FROM dbo.MaintenanceWaterHardnessBands bb
    WHERE bb.IsActive = 1
      AND (bb.MaxGrainsPerGallon IS NULL OR i.GrainsPerGallon <= bb.MaxGrainsPerGallon)
    ORDER BY bb.SortOrder ASC
) b;
GO

/* -------------------------------------------------------------------------
   Expected service life per asset, after water.

   The join that makes the modifier real: base expected life by template and
   tier, multiplied by the household's factor, but ONLY for protocols that run
   water. Everything else passes through untouched, and an untested household
   passes through untouched as well.

   WHERE THE TIER COMES FROM, and why not from the asset. MaintenanceAssets has
   no tier column -- tier is resolved from the brand through
   MaintenanceBrandTiers, and re-implementing that match here would be a second
   copy of a rule that already exists in two places. So this view takes the tier
   that was ACTUALLY USED, off the most recent field inspection, which is both
   already recorded and the figure the customer was shown. An asset nobody has
   inspected yet has no tier here and therefore no expected life: it reports
   NULL rather than a guess, and UsesWater and WaterLifeFactor are still
   populated so the dashboard can show the water finding regardless.
   ------------------------------------------------------------------------- */
IF OBJECT_ID('dbo.vw_MaintenanceAssetExpectedLife', 'V') IS NOT NULL
    DROP VIEW dbo.vw_MaintenanceAssetExpectedLife;
GO

CREATE VIEW dbo.vw_MaintenanceAssetExpectedLife
AS
WITH last_inspection AS (
    SELECT fi.AssetId, fi.LifecycleTierCode,
           ROW_NUMBER() OVER (PARTITION BY fi.AssetId
                              ORDER BY COALESCE(fi.CompletedAt, fi.StartedAt, fi.CreatedAt) DESC,
                                       fi.FieldInspectionId DESC) AS rn
    FROM dbo.MaintenanceFieldInspections fi
    WHERE fi.LifecycleTierCode IS NOT NULL
)
SELECT
    a.AssetId,
    a.HouseholdId,
    a.AssetTypeName,
    a.CheckpointSetCode AS TemplateCode,
    li.LifecycleTierCode AS TierCode,
    r.ExpectedYears AS BaseExpectedYears,
    CASE WHEN wb.TemplateCode IS NULL THEN CAST(0 AS BIT) ELSE CAST(1 AS BIT) END
        AS UsesWater,
    /* No test, or an appliance that never touches water, means no adjustment.
       COALESCE, not a default row: absence is the honest answer. */
    CASE WHEN wb.TemplateCode IS NULL THEN CAST(1.000 AS DECIMAL(4,3))
         ELSE COALESCE(w.LifeFactor, CAST(1.000 AS DECIMAL(4,3))) END AS WaterLifeFactor,
    CAST(ROUND(r.ExpectedYears *
        CASE WHEN wb.TemplateCode IS NULL THEN 1.000
             ELSE COALESCE(w.LifeFactor, 1.000) END, 1) AS DECIMAL(5,1))
        AS AdjustedExpectedYears,
    w.BandCode,
    w.GrainsPerGallon,
    w.IsFlaggedToCustomer
FROM dbo.MaintenanceAssets a
LEFT JOIN last_inspection li
    ON li.AssetId = a.AssetId AND li.rn = 1
LEFT JOIN dbo.MaintenanceExpectedLifeRules r
    ON r.TemplateCode = a.CheckpointSetCode
   AND r.TierCode = li.LifecycleTierCode
   AND r.IsActive = 1
LEFT JOIN dbo.MaintenanceWaterBearingProtocols wb
    ON wb.TemplateCode = a.CheckpointSetCode AND wb.IsActive = 1
LEFT JOIN dbo.vw_MaintenanceHouseholdWaterLatest w
    ON w.HouseholdId = a.HouseholdId;
GO

