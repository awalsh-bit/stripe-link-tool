CREATE VIEW dbo.vw_MaintenanceAssetAgeProvenance
AS
SELECT
    a.AssetId,
    a.HouseholdId,
    a.AssetTypeName,
    a.Brand,
    a.Model,
    a.InstallYear,
    a.InstallDate,
    COALESCE(a.AgeSourceCode, 'unknown') AS AgeSourceCode,
    COALESCE(s.DisplayName, 'Not established') AS AgeSourceName,
    COALESCE(s.IsDocumented, 0) AS IsDocumented,
    a.AgeSourceReference,
    /* NULL, not zero: an appliance with no install year has no age, and an age
       of 0 would read as brand new. */
    CASE WHEN a.InstallYear IS NULL THEN NULL
         ELSE YEAR(SYSUTCDATETIME()) - a.InstallYear END AS AgeYears,
    CASE WHEN a.InstallYear IS NULL THEN CAST(1 AS BIT) ELSE CAST(0 AS BIT) END AS ScoredOnConditionOnly
FROM dbo.MaintenanceAssets a
LEFT JOIN dbo.MaintenanceAgeSources s
    ON s.AgeSourceCode = a.AgeSourceCode;
