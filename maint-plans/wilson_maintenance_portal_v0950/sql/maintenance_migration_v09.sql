/* -------------------------------------------------------------------------
   7.10  Water hardness as a lifecycle modifier  (added v0.9.21)

   A property-level fact, not an appliance-level one. One hardness strip is run
   per residence per visit, and the reading changes how long the equipment that
   RUNS WATER is expected to last -- never what the technician measured today,
   and never anything on a dryer or a range.

   THE READING IS THE ONLY INPUT. A technician types the number off the strip;
   nobody selects a band and nobody selects a multiplier. The factor is computed
   from the number by piecewise-linear interpolation between the anchors in
   MaintenanceWaterLifeFactorAnchors, and vw_MaintenanceHouseholdWaterLatest
   below does that interpolation with the same anchors and the same clamps as
   WILSON_WATER.lifeFactorForGpg() in plan-config.js.

   There is no softener table. An earlier draft of this section had one, and it
   was double-counting: the strip is read at a tap, downstream of whatever
   equipment the house has, so a working softener already shows up as a soft
   reading. Recording it separately asked the same question twice and then
   needed a rule for what to do when the two answers disagreed.

   Four things this schema is deliberately built to prevent:

   1. AN ASSUMED READING. There is no default hardness and no lookup by ZIP.
      A household with no row here is untested, the application applies a factor
      of 1.00, and the customer report says the water has not been tested.
      Inferring hardness from an address would be inventing a measurement.

   2. A LOST HISTORY. Every test is a row. A jump from 3 gpg to 14 gpg between
      two visits is a softener that has failed since the last one -- which is a
      finding worth more to the customer than either reading alone, and is only
      visible if the earlier row survives.

   3. A STORED MULTIPLIER. The factor is nowhere in the data. It is derived, on
      read, from the reading and the current anchors -- so correcting the anchors
      corrects every house at once. A factor written onto the test row at save
      time would freeze today's inference into history and quietly outlive it.

   4. AN INFERENCE PASSING AS A STUDY. IsSourced on the settings row is 0 and
      is meant to stay 0 until somebody puts a real lifespan study behind these
      numbers. The anchors are Wilson's inference from a water-heater EFFICIENCY
      study, and the basis text says so wherever the figure is shown.
   ------------------------------------------------------------------------- */

