CREATE VIEW dbo.vw_MaintenanceScoringCheckpoints
AS
SELECT
    c.ProtocolCheckpointId,
    c.ProtocolTemplateId,
    t.TemplateCode,
    t.TemplateVersion,
    c.CheckpointCode,
    c.CheckpointName,
    c.ResultKind,
    c.AnswerControl,
    c.OptionSetCode,
    c.ReadingLabel,
    c.ReadingUnit,
    c.SortOrder
FROM dbo.MaintenanceProtocolCheckpoints c
INNER JOIN dbo.MaintenanceProtocolTemplates t
    ON t.ProtocolTemplateId = c.ProtocolTemplateId
WHERE c.IsActive = 1
  AND c.ScoresHealth = 1
  AND c.ResultKind = 'scored';
GO

