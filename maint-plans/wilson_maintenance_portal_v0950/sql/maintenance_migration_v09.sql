           a row carries no ExpectedYears and no AnchoredYears, because the
           anchored half depends on which line it lands on: the same 15 resolves
           to 17 against the hood column and 18 against the range column. The
           consumer computes the midpoint at lookup, rounding halves UP. */
        LineCode NVARCHAR(40) NOT NULL,
        /* NULL for a brand's plain row. A series row is checked FIRST and
           matches on text found in the model number or description. */
        SeriesCode NVARCHAR(60) NULL,
        SeriesLabel NVARCHAR(80) NULL,
        SeriesMatchText NVARCHAR(MAX) NULL,
        TierCode NVARCHAR(30) NOT NULL,
        /* The shipped figure, and the two numbers it is the midpoint of.
           FieldYears is Wilson's service experience; AnchoredYears is
           MaintenanceExpectedLife for this line and tier. Both are kept so a
           number nobody agrees with can be argued with rather than only
           overwritten. */
        ExpectedYears DECIMAL(5,1) NULL,
        FieldYears DECIMAL(5,1) NOT NULL,
        AnchoredYears DECIMAL(5,1) NULL,
        /* Brand-wide rows only: the lines that brand actually sells, as a JSON
           array. A brand-wide row must answer on nothing outside it -- Asko has
           no outdoor grill and Bertazzoni no coffee system. An EMPTY or absent
           list must mean "no lines", never "all lines". CoversDrafted marks a
           list drafted from public catalogues rather than confirmed by Wilson. */
        CoversLines NVARCHAR(MAX) NULL,
        CoversDrafted BIT NOT NULL
            CONSTRAINT DF_MaintenanceBrandLifespans_Drafted DEFAULT (0),
        /* Whose judgement the row's tier was. Tier chooses the column
           AnchoredYears comes from, so it moves the number. */
        TierDrafted BIT NOT NULL
            CONSTRAINT DF_MaintenanceBrandLifespans_TierDrafted DEFAULT (0),
        /* Set when FieldYears stands ALONE because no published figure covers
           this equipment -- outdoor undercounter refrigeration and ice, where
           NAHB's rows are indoor machines, and built-in coffee, whose columns
           were drafted from the one row that would be averaged against them.
           AnchoredYears is NULL and ExpectedYears equals FieldYears. */
        NoAnchorReason NVARCHAR(400) NULL,
        /* A named line must ship its resolved figure; a brand-wide row must NOT,
           or one line's column would be silently applied to all of them. */
        CONSTRAINT CK_MaintenanceBrandLifespans_Resolved CHECK (
            (LineCode <> '*' AND ExpectedYears IS NOT NULL
             /* Unanchored means the field figure stands alone, and says why. */
             AND (AnchoredYears IS NOT NULL
