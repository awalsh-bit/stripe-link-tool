/* -------------------------------------------------------------------------
   v0.9.19: THE ANSWERS A CHECKPOINT ACCEPTS, AND WHAT EACH ONE IS WORTH.

   Conditions score now. The reason that is defensible rather than reckless is
   that the value of every answer is written down in advance, shown to the
   technician on the button, and identical on every visit and every appliance --
   so "cloudy or incomplete cubes" is worth the same 3 whoever taps it.

   Those values lived only in plan-config.js, which is fine while the browser
   computes the score and useless the moment the dashboard has to. This table is
   where they live in SQL Server, seeded from the same config, with the parity
   asserted by _qa/verify-sql-migration.py.

       ScoreValue     1-5, or NULL for "could not get to it", which scores
                      nothing and is never a failure
       RaisesFinding  independent of the score: heavy build-up beyond reach is
                      worth a 3 AND needs saying out loud, and a full-marks
                      answer never raises one
       RequiresDetail the answer owes a follow-up ('code' so far) and the check
                      is not complete without it

   CK_..._ScoreRange is the guardrail: a score outside 1-5 cannot be stored, so
   a bad seed fails the insert instead of quietly deflating somebody's report.
