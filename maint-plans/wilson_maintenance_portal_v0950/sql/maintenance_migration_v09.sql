/* -------------------------------------------------------------------------
   v0.9.17: WHAT KIND OF ANSWER A CHECKPOINT TAKES, IN THE DATABASE.

   Until now every checkpoint carried a rating and every rating averaged into
   the health score. That is how "Maintenance clean cycle -- performed" -- work
   Wilson was paid to do -- ended up raising the customer's number, and how a
   technician's judgement of an evaporator frost pattern carried the same weight
   as a measured compartment temperature.

   The browser now resolves this through WILSON_ANSWERS.scorable() in
   plan-config.js. These columns carry the same rule into SQL Server, because
   the dashboard will eventually compute the score here, and a rule that lives
   in only one of the two places is a rule that will disagree with itself.

       ResultKind    scored | maintenance | observed | trend
       ScoresHealth  1 only where ResultKind = 'scored', enforced below
       AnswerControl which tap-only control the field tool renders
       OptionSetCode the observation or pass/fail set the options come from

   CK_..._ScoresOnlyScored is the guardrail, not documentation: it makes
   "work performed raises the health score" unrepresentable rather than merely
   discouraged. Any future seed that tries it fails the insert.
   ------------------------------------------------------------------------- */
